from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import landscape, A4
from reportlab.lib.units import mm
from reportlab.pdfbase.pdfmetrics import stringWidth
from reportlab.pdfgen import canvas


def _fit_text(pdf: canvas.Canvas, text: str, font: str, initial_size: int, max_width: float) -> int:
    size = initial_size
    while size > 14 and stringWidth(text, font, size) > max_width:
        size -= 1
    return size


def create_certificate(path: Path, recipient_name: str, title: str, issuer: str) -> None:
    """Create one fixed-layout certificate PDF."""
    path.parent.mkdir(parents=True, exist_ok=True)
    page_width, page_height = landscape(A4)
    pdf = canvas.Canvas(str(path), pagesize=(page_width, page_height))
    pdf.setFillColor(colors.HexColor("#F8F5ED"))
    pdf.rect(0, 0, page_width, page_height, fill=1, stroke=0)
    pdf.setStrokeColor(colors.HexColor("#12355B"))
    pdf.setLineWidth(3)
    pdf.rect(12 * mm, 12 * mm, page_width - 24 * mm, page_height - 24 * mm, fill=0, stroke=1)
    pdf.setStrokeColor(colors.HexColor("#C89B3C"))
    pdf.setLineWidth(1)
    pdf.rect(17 * mm, 17 * mm, page_width - 34 * mm, page_height - 34 * mm, fill=0, stroke=1)
    pdf.setFillColor(colors.HexColor("#12355B"))
    pdf.setFont("Helvetica-Bold", 30)
    pdf.drawCentredString(page_width / 2, page_height - 48 * mm, "CERTIFICATE OF COMPLETION")
    pdf.setFillColor(colors.HexColor("#555555"))
    pdf.setFont("Helvetica", 14)
    pdf.drawCentredString(page_width / 2, page_height - 68 * mm, "This is proudly presented to")
    name_size = _fit_text(pdf, recipient_name, "Helvetica-Bold", 34, page_width - 100 * mm)
    pdf.setFillColor(colors.HexColor("#12355B"))
    pdf.setFont("Helvetica-Bold", name_size)
    pdf.drawCentredString(page_width / 2, page_height - 92 * mm, recipient_name)
    pdf.setStrokeColor(colors.HexColor("#C89B3C"))
    pdf.setLineWidth(1.5)
    pdf.line(page_width / 2 - 70 * mm, page_height - 98 * mm, page_width / 2 + 70 * mm, page_height - 98 * mm)
    pdf.setFillColor(colors.HexColor("#555555"))
    pdf.setFont("Helvetica", 14)
    pdf.drawCentredString(page_width / 2, page_height - 116 * mm, "for successfully completing")
    title_size = _fit_text(pdf, title, "Helvetica-Bold", 22, page_width - 90 * mm)
    pdf.setFillColor(colors.HexColor("#12355B"))
    pdf.setFont("Helvetica-Bold", title_size)
    pdf.drawCentredString(page_width / 2, page_height - 134 * mm, title)
    pdf.setFillColor(colors.HexColor("#555555"))
    pdf.setFont("Helvetica", 11)
    pdf.drawCentredString(page_width / 2, 42 * mm, f"Issued by {issuer}")
    pdf.drawCentredString(page_width / 2, 34 * mm, "Generated by the Bulk Certificate Generator")
    pdf.save()
